"""Complete FR/LG encounter tables.

Data sourced from Bulbapedia and Serebii. Each route's encounter slots
sum to 1.0 for a given encounter type. Where Fire Red and Leaf Green
differ, separate entries exist per version.

Only grass/cave encounters are included in this initial version.
Surf, fishing, and Sevii Islands can be added later.
"""

from shiny_pokemon.data.routes import (
    EncounterSlot as E,
    EncounterType,
    GameVersion,
    RouteData,
)

# Shorthand
GRASS = EncounterType.GRASS
CAVE = EncounterType.CAVE
SURF = EncounterType.SURF
OLD_ROD = EncounterType.OLD_ROD
GOOD_ROD = EncounterType.GOOD_ROD
SUPER_ROD = EncounterType.SUPER_ROD
FR = GameVersion.FIRE_RED
LG = GameVersion.LEAF_GREEN


def _route(name: str, etype: EncounterType, *slots: E) -> RouteData:
    return RouteData(name=name, encounter_type=etype, encounter_slots=tuple(slots))


